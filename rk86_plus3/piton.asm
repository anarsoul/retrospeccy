; "Питон" для "Радио-86РК" - запись 26 кассеты green_svema как есть, кроме
; двух вещей:
;   - число строк: у РК их 25, у эмулятора 24. Нижняя рамка, длина боковых
;     стенок, место старта и надпись "НАЖМИТЕ <ВК>" подняты на строку;
;   - адреса видеопамяти: файл на ленте собран под РК с 16К (#37C2), здесь
;     видеопамять на обычном месте РК с 32К (#77C2).
;   - управление: вместо стрелок (#08, #18, #19, #1A) - O, P, Q, A.
; DI/EI в игре нет, звук - только звонок (код 7) через Монитор.
; Лента - в формате, который читает директива I эмулятора.
;
; Сборка:  sjasmplus piton.asm  ->  piton.tap

        DEVICE ZXSPECTRUM48

        ORG #1100
piton:  INCBIN "../green_svema/side_1/svema_26/02_RADIO_FILE.bin"
piton_end:

        ORG #113E
        DW #77C2                ; было #37C2: левый верхний угол рамки
        ORG #114B
        DW #77C2 + 23 * 78      ; было #3F12: нижняя рамка, строка 24
        ORG #1156
        DB 24                   ; было 25: правая стенка
        ORG #115C
        DB 24                   ; было 25: левая стенка
        ORG #1167
        DW #77C2 + 22 * 78 + 30 ; было #3EE2: голова в начале игры
        ORG #117E
        DB 'O'                  ; было #08: влево
        ORG #1186
        DB 'P'                  ; было #18: вправо
        ORG #118E
        DB 'Q'                  ; было #19: вверх
        ORG #1196
        DB 'A'                  ; было #1A: вниз
        ORG #11F5
        DW #77C2 + 37           ; было #37E7: младшая цифра счётчика длины
        ORG #1274
        DB ' ' + 23             ; было #38: строка надписи "НАЖМИТЕ <ВК>"

        EMPTYTAP "piton.tap"
        SAVETAP "piton.tap",CODE,"RADIO FILE",piton,piton_end - piton
