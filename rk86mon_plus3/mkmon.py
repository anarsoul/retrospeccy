#!/usr/bin/env python3
"""Make the Radio-86RK Monitor for 32K machines from the copy on the tape.

green_svema, side 1, record 31 ("MONIOK-1") is the Monitor of the 16K
Radio-86RK, typed in by hand: system variables at #3600, video memory at
#36D0.  The Monitor of the 32K machine is the same code with those addresses
#4000 higher - 80 high bytes of address operands, listed below (offsets from
#F800).  The result is byte for byte the well-known 32K Monitor ROM.

Usage: mkmon.py MONIOK-1.bin mon32.bin
"""
import sys

HIGH_BYTES = [
    0x03D, 0x043, 0x046, 0x04E, 0x051, 0x05D, 0x060, 0x066, 0x06B, 0x06E,
    0x085, 0x097, 0x09C, 0x0A0, 0x0F0, 0x11E, 0x12E, 0x131, 0x139, 0x13F,
    0x142, 0x148, 0x14E, 0x155, 0x248, 0x24C, 0x25C, 0x264, 0x267, 0x27D,
    0x282, 0x288, 0x290, 0x2F1, 0x334, 0x3AA, 0x3D6, 0x3FB, 0x408, 0x415,
    0x42B, 0x42F, 0x436, 0x464, 0x474, 0x48C, 0x4C7, 0x4CB, 0x4CE, 0x4EC,
    0x551, 0x554, 0x587, 0x58B, 0x5A5, 0x5B7, 0x60B, 0x611, 0x61E, 0x624,
    0x628, 0x640, 0x646, 0x65B, 0x65F, 0x66D, 0x670, 0x686, 0x71C, 0x754,
    0x758, 0x7A4, 0x7A9, 0x7AE, 0x7B5, 0x7BB, 0x7BE, 0x7C5, 0x7CE, 0x7DB,
]

rom = bytearray(open(sys.argv[1], 'rb').read())
assert len(rom) == 2048 and len(HIGH_BYTES) == 80
for i in HIGH_BYTES:
    assert 0x35 <= rom[i] <= 0x3F, hex(i)
    rom[i] += 0x40
open(sys.argv[2], 'wb').write(rom)
